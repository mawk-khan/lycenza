    |
    */

    // Phase 0O.3 (ADR 0049 section 5): a fixed, non-secret prefix so a
    // leaked human token is recognisable (partner keys use `lyc_pk_`).
    'token_prefix' => 'lyc_pat_',

    /*
    |--------------------------------------------------------------------------
    | Sanctum Middleware
    |--------------------------------------------------------------------------
