<?php

namespace Tests\Feature\Postgres;

use App\Support\Operations\CheckResult;
use App\Support\Operations\DatabaseRoleVerifier;
use Illuminate\Support\Facades\DB;
use PHPUnit\Framework\Attributes\Test;
use Tests\TestCase;

/**
 * HR.R1-C29 (C14-N5): `platform:verify-database` keeps the credential-verification backstops as shipped. Every
 * break is committed through the owner connection on the isolated test database, restored in `finally`, and the
 * check passes again after each.
 */
class HrCredentialVerificationVerifierTest extends TestCase
{
    private function check(string $code): CheckResult
    {
        return collect(app(DatabaseRoleVerifier::class)->verify())->keyBy('code')[$code];
    }

    #[Test]
    public function the_checks_pass_on_the_real_schema(): void
    {
        foreach (['hr_credential_verification_invariants', 'hr_family_trigger_functions', 'hr_family_runtime_privileges'] as $code) {
            $this->assertSame(CheckResult::PASS, $this->check($code)->status, "{$code}: ".$this->check($code)->note);
        }
        $this->assertSame('SI', DatabaseRoleVerifier::HR_FAMILY_RUNTIME_PRIVILEGES['employee_credential_verifications']);
        $this->assertCount(57, DatabaseRoleVerifier::HR_FAMILY_RUNTIME_PRIVILEGES, 'the 56 tables of C26 and the decisions of C29');
    }

    #[Test]
    public function each_break_fails_the_check_that_owns_it_and_names_it(): void
    {
        $admin = DB::connection('pgsql_admin');
        $function = (string) $admin->selectOne("select pg_get_functiondef('public.employee_credential_verifications_guard()'::regprocedure) as d")->d;
        $revisionCheck = (string) $admin->selectOne("select pg_get_constraintdef(oid) as d from pg_constraint where conname = 'employee_qualifications_verification_revision_check'")->d;
        $fk = (string) $admin->selectOne("select pg_get_constraintdef(oid) as d from pg_constraint where conname = 'employee_credential_verifications_qualification_fk'")->d;

        $breaks = [
            // A guard body rewritten with its SET clause kept (C28-N3 asks this of new guards).
            [str_replace('a decision binds the current revision', 'a decision may bind any revision', $function), $function, 'hr_credential_verification_invariants', 'employee_credential_verifications_guard:shipped'],
            ['ALTER TABLE employee_qualifications DROP CONSTRAINT employee_qualifications_verification_revision_check; ALTER TABLE employee_qualifications ADD CONSTRAINT employee_qualifications_verification_revision_check CHECK (true)',
                "ALTER TABLE employee_qualifications DROP CONSTRAINT employee_qualifications_verification_revision_check; ALTER TABLE employee_qualifications ADD CONSTRAINT employee_qualifications_verification_revision_check {$revisionCheck}",
                'hr_credential_verification_invariants', 'employee_qualifications_verification_revision_check:shipped'],
            // A decision that would hold its credential instead of leaving with it.
            ['ALTER TABLE employee_credential_verifications DROP CONSTRAINT employee_credential_verifications_qualification_fk; ALTER TABLE employee_credential_verifications ADD CONSTRAINT employee_credential_verifications_qualification_fk FOREIGN KEY (qualification_id, employee_id, school_id) REFERENCES employee_qualifications(id, employee_id, school_id)',
                "ALTER TABLE employee_credential_verifications DROP CONSTRAINT employee_credential_verifications_qualification_fk; ALTER TABLE employee_credential_verifications ADD CONSTRAINT employee_credential_verifications_qualification_fk {$fk}",
                'hr_credential_verification_invariants', 'employee_credential_verifications_qualification_fk'],
            ['ALTER TABLE employee_credential_verifications ALTER COLUMN sequence SET GENERATED BY DEFAULT', 'ALTER TABLE employee_credential_verifications ALTER COLUMN sequence SET GENERATED ALWAYS', 'hr_credential_verification_invariants', 'employee_credential_verifications:sequence'],
            ['GRANT UPDATE ON SEQUENCE employee_credential_verifications_sequence_seq TO school_os_app', 'REVOKE UPDATE ON SEQUENCE employee_credential_verifications_sequence_seq FROM school_os_app', 'hr_credential_verification_invariants', 'employee_credential_verifications:sequence_privileges'],
            ['ALTER TABLE employee_credential_verifications NO FORCE ROW LEVEL SECURITY', 'ALTER TABLE employee_credential_verifications FORCE ROW LEVEL SECURITY', 'hr_credential_verification_invariants', 'employee_credential_verifications:rls'],
            ['GRANT UPDATE ON employee_credential_verifications TO school_os_app', 'REVOKE UPDATE ON employee_credential_verifications FROM school_os_app', 'hr_family_runtime_privileges', 'employee_credential_verifications'],
            ['ALTER TABLE employee_qualifications DISABLE TRIGGER trg_employee_qualifications_revision_guard', 'ALTER TABLE employee_qualifications ENABLE TRIGGER trg_employee_qualifications_revision_guard', 'hr_family_trigger_functions', 'trg_employee_qualifications_revision_guard:disabled'],
            ['DROP TRIGGER trg_employee_credential_verifications_apply ON employee_credential_verifications',
                'CREATE TRIGGER trg_employee_credential_verifications_apply AFTER INSERT ON employee_credential_verifications FOR EACH ROW EXECUTE FUNCTION public.employee_credential_verifications_apply()',
                'hr_family_trigger_functions', 'trg_employee_credential_verifications_apply:missing'],
        ];

        foreach ($breaks as [$break, $restore, $code, $named]) {
            $admin->unprepared($break);
            try {
                $result = $this->check($code);
                $this->assertSame(CheckResult::FAIL, $result->status, "detects: {$break}");
                $this->assertStringContainsString($named, $result->note, $break);
            } finally {
                $admin->unprepared($restore);
            }
            $this->assertSame(CheckResult::PASS, $this->check($code)->status, "after: {$restore}");
        }
        $this->assertSame($function, (string) $admin->selectOne("select pg_get_functiondef('public.employee_credential_verifications_guard()'::regprocedure) as d")->d, 'the guard is restored exactly');
    }
}
